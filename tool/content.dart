// Content helper: tick topics, start posts and subjects, check everything.
//
//   dart run tool/content.dart done <subject> "<topic>" [--date 2026-11-02]   tick a topic (today by default)
//   dart run tool/content.dart doing <subject> "<topic>"                      mark it as being studied now
//   dart run tool/content.dart undo <subject> "<topic>"                       back to not done
//   dart run tool/content.dart status                                         the roadmap, in the terminal
//   dart run tool/content.dart new-post "Title" [--tags "A, B"] [--subjects "anatomy"] [--emoji 🦴] [--folder]
//   dart run tool/content.dart new-subject <part> "Title" [--tr "Türkçe adı"] [--emoji 🦴]
//   dart run tool/content.dart check     find broken images, bad front matter and unknown subjects
//   dart run tool/content.dart sync      register content folders in pubspec.yaml
//   dart run tool/content.dart bundle    all text content in one file, for a faster start
//
// <subject> is the subject's id (the file name without its number, e.g.
// `anatomy`, `internal-medicine`), its title, or the start of either.
// <topic> only needs to be a part of the topic's name.
//
// Flutter only bundles folders listed in pubspec.yaml, so the commands that
// make folders run `sync` for you. Run it yourself after adding folders by hand.
import 'dart:convert';
import 'dart:io';

import 'package:ceren_bingol_blog/content/content_repository.dart';
import 'package:ceren_bingol_blog/content/markdown_blocks.dart';
import 'package:ceren_bingol_blog/content/models.dart';
import 'package:ceren_bingol_blog/content/text_utils.dart';
import 'package:yaml/yaml.dart';

const _begin = '    # >>> content (generated by `dart run tool/content.dart sync`, do not edit)';
const _end = '    # <<< content';

void main(List<String> arguments) {
  if (arguments.isEmpty) return _usage();
  final args = arguments.skip(1).toList();
  switch (arguments.first) {
    case 'done':
      _setTopic(args, 'x');
    case 'doing':
      _setTopic(args, '/');
    case 'undo':
      _setTopic(args, ' ');
    case 'status':
      _status();
    case 'new-post':
      _newPost(args);
    case 'new-subject':
      _newSubject(args);
    case 'check':
      exitCode = _check() ? 0 : 1;
    case 'sync':
      _sync();
    case 'bundle':
      _bundle();
    default:
      _usage();
  }
}

void _usage() {
  stdout.writeln('''
Usage:
  dart run tool/content.dart done <subject> "<topic>" [--date 2026-11-02]
  dart run tool/content.dart doing <subject> "<topic>"
  dart run tool/content.dart undo <subject> "<topic>"
  dart run tool/content.dart status
  dart run tool/content.dart new-post "Title" [--tags "A, B"] [--subjects "anatomy"] [--emoji 🦴] [--folder]
  dart run tool/content.dart new-subject <part> "Title" [--tr "Türkçe adı"] [--emoji 🦴]
  dart run tool/content.dart check
  dart run tool/content.dart sync''');
}

String _today() => DateTime.now().toIso8601String().substring(0, 10);

String _yamlString(String s) => '"${s.replaceAll(r'\', r'\\').replaceAll('"', r'\"')}"';

/// Takes `--name value` out of [args] and returns the value.
String? _option(List<String> args, String name) {
  final i = args.indexOf('--$name');
  if (i < 0 || i + 1 >= args.length) return null;
  final value = args[i + 1];
  args.removeRange(i, i + 2);
  return value;
}

void _fail(String message) {
  stderr.writeln(message);
  exitCode = 1;
}

Map<String, String> _contentFiles() => {
  for (final f in Directory('content').listSync(recursive: true).whereType<File>())
    if (isContentTextFile(f.path)) f.path.replaceAll(r'\', '/'): f.readAsStringSync(),
};

ContentRepository _content() => ContentRepository.fromFiles(_contentFiles(), includeDrafts: true);

Subject? _findSubject(ContentRepository content, String query) {
  final q = slugify(query);
  return content.subject(q) ??
      content.subjects.where((s) => slugify(s.title) == q || slugify(s.titleTr ?? '') == q).firstOrNull ??
      content.subjects.where((s) => s.id.startsWith(q) || slugify(s.title).startsWith(q)).singleOrNull;
}

final _checkLine = RegExp(r'^(\s*[-*+]\s+\[)[ xX/~](\]\s+)(.*?)\s*$');
final _endDate = RegExp(r'\s*(?:[-–—·•@|,]\s*)?\(?\s*\d{4}-\d{2}-\d{2}\s*\)?\s*$');

/// Sets a topic's box to [mark]: `x` done (with a date), `/` studying, ` ` to do.
void _setTopic(List<String> args, String mark) {
  final date = _option(args, 'date') ?? _today();
  if (args.length < 2) return _usage();
  if (DateTime.tryParse(date) == null) return _fail('"$date" isn\'t a date. Write it like 2026-11-02.');
  final content = _content();
  final subject = _findSubject(content, args.first);
  if (subject == null) {
    return _fail('No subject called "${args.first}". The subjects are:\n  ${content.subjects.map((s) => s.id).join(', ')}');
  }

  final query = args.skip(1).join(' ').toLowerCase().trim();
  final file = File(subject.assetPath);
  final lines = file.readAsStringSync().replaceAll('\r\n', '\n').split('\n');
  final matches = <int>[];
  var inComment = false;
  var inFence = false;
  for (var i = 0; i < lines.length; i++) {
    final line = lines[i];
    if (line.trimLeft().startsWith('```') || line.trimLeft().startsWith('~~~')) inFence = !inFence;
    final opens = line.contains('<!--');
    final skip = inFence || inComment || opens;
    if (opens && !line.substring(line.indexOf('<!--')).contains('-->')) inComment = true;
    if (inComment && !opens && line.contains('-->')) inComment = false;
    if (skip) continue;
    final item = CheckItem.tryParse(line);
    if (item == null) continue;
    final text = item.text.toLowerCase();
    if (text == query) {
      matches
        ..clear()
        ..add(i);
      break;
    }
    if (text.contains(query)) matches.add(i);
  }

  if (matches.isEmpty) {
    return _fail('No topic matching "$query" in ${subject.title}. Its topics are:\n'
        '${subject.topics.map((t) => '  - ${t.text}').join('\n')}');
  }
  if (matches.length > 1) {
    return _fail('More than one topic in ${subject.title} matches "$query":\n'
        '${matches.map((i) => '  - ${CheckItem.tryParse(lines[i])!.text}').join('\n')}\nWrite a bit more of the name.');
  }

  final i = matches.single;
  final m = _checkLine.firstMatch(lines[i])!;
  final text = m.group(3)!.replaceFirst(_endDate, '');
  lines[i] = '${m.group(1)}$mark${m.group(2)}$text${mark == 'x' ? ' ($date)' : ''}';
  file.writeAsStringSync(lines.join('\n'));

  final updated = _content().subject(subject.id)!;
  final topic = CheckItem.tryParse(lines[i])!.text;
  final verb = switch (mark) {
    'x' => 'Ticked off',
    '/' => 'Now studying',
    _ => 'Unticked',
  };
  stdout.writeln('🐾 $verb "$topic" in ${updated.title}: ${updated.doneCount}/${updated.topicCount} topics done.');
  if (mark == 'x' && updated.status == SubjectStatus.done) {
    stdout.writeln('🎉 That was the last one. ${updated.title} is finished!');
  }
}

void _status() {
  final content = _content();
  String bar(double value, int width) {
    final full = (value * width).round();
    return '${'█' * full}${'░' * (width - full)}';
  }

  final percent = (content.progress * 100).round();
  stdout.writeln('\n🐾 The road to TUS: ${content.doneTopicCount}/${content.topicCount} topics, $percent%\n');
  for (final part in content.parts) {
    stdout.writeln('${part.title.padRight(34)} ${bar(part.progress, 16)} ${(part.progress * 100).round()}%');
    for (final s in part.subjects) {
      final mark = switch (s.status) {
        SubjectStatus.done => '✔',
        SubjectStatus.doing => '✎',
        SubjectStatus.todo => '·',
      };
      stdout.writeln('  $mark ${s.title.padRight(30)} ${bar(s.progress, 10)} ${'${s.doneCount}/${s.topicCount}'.padLeft(5)}   ${s.id}');
    }
    stdout.writeln();
  }
  final current = content.currentSubject;
  final next = current?.nextTopic;
  if (current != null && next != null) stdout.writeln('Next up: ${next.text} (${current.title})');
}

void _newPost(List<String> args) {
  final folder = args.remove('--folder');
  final tags = (_option(args, 'tags') ?? '').split(',').map((t) => t.trim()).where((t) => t.isNotEmpty);
  final subjects = (_option(args, 'subjects') ?? '').split(',').map(slugify).where((t) => t.isNotEmpty);
  final emoji = _option(args, 'emoji') ?? '🐾';
  if (args.isEmpty) return _usage();
  final title = args.join(' ');
  final name = '${_today()}-${slugify(title)}';
  final file = folder ? File('content/blog/$name/index.md') : File('content/blog/$name.md');
  if (file.existsSync()) return _fail('${file.path} already exists.');

  file
    ..createSync(recursive: true)
    ..writeAsStringSync('''
---
title: ${_yamlString(title)}
description: One or two sentences for the post's card.
tags: [${tags.join(', ')}]
subjects: [${subjects.join(', ')}]   # roadmap subjects the post is about, e.g. [anatomy, physiology]
emoji: $emoji        # shown on the cover when there's no image
# image: cover.jpg   # a cover picture next to this file (start the post with --folder)
# featured: true     # pin it to the top of the blog
draft: true          # only shows on your computer; delete this line to publish
---

The first paragraph is the hook: it shows on the post's card.

<!-- truncate -->

## What I studied

## How I studied it

## What worked (and what didn't)
''');
  stdout.writeln('Created ${file.path}');
  if (folder) _sync();
}

void _newSubject(List<String> args) {
  final tr = _option(args, 'tr');
  final emoji = _option(args, 'emoji') ?? '📘';
  if (args.length < 2) return _usage();
  final part = slugify(args.first);
  final title = args.skip(1).join(' ');
  final dir = Directory('content/roadmap/$part');
  final newPart = !dir.existsSync();
  dir.createSync(recursive: true);
  if (newPart) {
    File('${dir.path}/_part_.yaml').writeAsStringSync('''
title: ${_yamlString(humanize(part))}
# title_tr: Türkçe adı
short: ${_yamlString(humanize(part))}   # used on the tabs
emoji: 🐾
position: 9                     # order on the roadmap
# description: One line about this part.
''');
    stdout.writeln('Created ${dir.path}/_part_.yaml');
  }

  var last = 0;
  for (final f in dir.listSync().whereType<File>()) {
    final number = RegExp(r'(\d+)-[^/\\]*\.md$').firstMatch(f.path)?.group(1);
    if (number != null && int.parse(number) > last) last = int.parse(number);
  }
  final file = File('${dir.path}/${(last + 1).toString().padLeft(2, '0')}-${slugify(title)}.md');
  if (file.existsSync()) return _fail('${file.path} already exists.');
  file.writeAsStringSync('''
---
title: ${_yamlString(title)}
${tr == null ? '# title_tr: Türkçe adı' : 'title_tr: ${_yamlString(tr)}'}
emoji: $emoji
# color: mint     # pink, peach, butter, mint, sky, lilac, coral or sage
description: One line about the subject.
---

<!--
  Tick a topic when it's done, with the date at the end:  - [x] Topic (2026-11-02)
  Studying it right now? Mark it  - [/] Topic
  Anything else you write here (notes, resources, tips) shows on the subject's page.
-->

## Topics

- [ ] First topic
- [ ] Second topic
''');
  stdout.writeln('Created ${file.path}');
  if (newPart) _sync();
}

/// Reports images that don't exist, front matter that doesn't parse, posts
/// about subjects that don't exist, and subjects without topics.
bool _check() {
  var problems = 0;
  void problem(String message) {
    stdout.writeln('✗ $message');
    problems++;
  }

  final files = _contentFiles();
  for (final MapEntry(key: path, value: text) in files.entries) {
    final yamlSource = path.endsWith('.md') ? RegExp(r'^---[ \t]*\r?\n([\s\S]*?)\r?\n---').firstMatch(text)?.group(1) : text;
    try {
      if (yamlSource != null && yamlSource.trim().isNotEmpty) loadYaml(yamlSource);
    } catch (e) {
      problem('$path: the settings between the --- lines aren\'t valid YAML (${e.toString().split('\n').first})');
    }

    final dir = path.substring(0, path.lastIndexOf('/'));
    // Examples in `code` aren't real images.
    final prose = text.replaceAll(RegExp(r'```[\s\S]*?```'), '').replaceAll(RegExp(r'`[^`\n]*`'), '');
    final refs = [
      for (final m in RegExp(r'!\[[^\]]*\]\(([^)\s]+)').allMatches(prose)) m.group(1)!,
      for (final m in RegExp(r'^(?:image|avatar):\s*(\S+)', multiLine: true).allMatches(prose)) m.group(1)!,
    ];
    for (final ref in refs) {
      if (RegExp(r'^https?://').hasMatch(ref)) continue;
      final resolved = ref.startsWith('/') ? 'content$ref' : Uri(path: '$dir/').resolve(ref).path;
      if (!File(Uri.decodeFull(resolved)).existsSync()) problem('$path: missing image "$ref"');
    }
  }

  final content = ContentRepository.fromFiles(files, includeDrafts: true);
  final seen = <String, String>{};
  for (final s in content.subjects) {
    final other = seen[s.id];
    if (other != null) problem('two subjects have the id "${s.id}": $other and ${s.assetPath}');
    seen[s.id] = s.assetPath;
    if (s.topics.isEmpty) stdout.writeln('! ${s.assetPath}: no topics yet (add lines like "- [ ] Topic")');
  }
  for (final post in content.posts) {
    for (final id in post.subjectIds) {
      if (content.subject(id) == null) problem('${post.assetPath}: there\'s no roadmap subject "$id"');
    }
  }
  stdout.writeln(problems == 0 ? '🐾 All good.' : '$problems problem(s) found.');
  return problems == 0;
}

/// Rewrites the generated asset block in pubspec.yaml with every folder under content/.
void _sync() {
  final dirs = <String>['content/'];
  for (final entity in Directory('content').listSync(recursive: true)) {
    if (entity is! Directory) continue;
    final path = entity.path.replaceAll(r'\', '/');
    if (path.split('/').any((part) => part.startsWith('.'))) continue;
    if (path.contains(' ')) stderr.writeln('warning: "$path" has spaces in its name; use dashes instead.');
    dirs.add('$path/');
  }
  dirs.sort();

  final pubspec = File('pubspec.yaml');
  final text = pubspec.readAsStringSync();
  final start = text.indexOf(_begin);
  final end = text.indexOf(_end);
  if (start < 0 || end < 0) return _fail('Could not find the content markers in pubspec.yaml.');
  final block = [_begin, for (final d in dirs) '    - $d', _end].join('\n');
  final updated = text.replaceRange(start, end + _end.length, block);
  if (updated != text) pubspec.writeAsStringSync(updated);
  stdout.writeln('Registered ${dirs.length} content folders in pubspec.yaml.');
}

/// Writes every Markdown and YAML file under content/ into
/// assets/generated/content.json, so the site fetches one file on startup
/// instead of one per page. Release builds use it; the deploy workflow runs it.
void _bundle() {
  final files = _contentFiles();
  File('assets/generated/content.json')
    ..createSync(recursive: true)
    ..writeAsStringSync(jsonEncode(files));
  stdout.writeln('Bundled ${files.length} files into assets/generated/content.json');
}
